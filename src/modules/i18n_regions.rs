pub fn get_jurisdiction_profile(country_code: &str) -> &'static CountryJurisdictionProfile {
    let clean = country_code.trim().to_uppercase();
    JURISDICTIONS
        .iter()
        .find(|j| j.code == clean)
        .unwrap_or(&JURISDICTIONS[0])
}

pub fn get_all_jurisdictions() -> &'static [CountryJurisdictionProfile] {
    JURISDICTIONS
}
